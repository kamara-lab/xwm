"""Shared Modal setup: one image and one runner, reused by every app.

Each experiment gets its own :class:`modal.App` (see ``deploy/app_*.py``) so the
six can run concurrently on separate GPUs and be started, watched and stopped
independently -- one failing experiment then does not take the others with it.
Everything they have in common lives here.
"""

