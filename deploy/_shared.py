def volume_for(experiment: str) -> modal.Volume:
    """A volume per experiment, so concurrent runs cannot clobber each other."""
    return modal.Volume.from_name(f"xwm-outputs-{experiment}", create_if_missing=True)


def report_device() -> None:
    """Print what we actually got, rather than assuming the GPU is there."""
    import subprocess

    try:
        smi = subprocess.run(  # noqa: S603
            ["nvidia-smi", "--query-gpu=name,memory.total,driver_version",
             "--format=csv,noheader"],
            capture_output=True, text=True, check=False,
        )
        print(f"nvidia-smi: {smi.stdout.strip() or smi.stderr.strip()}", flush=True)
    except FileNotFoundError:
        print("nvidia-smi: not found", flush=True)

    import jax

    print(f"jax {jax.__version__} devices: {jax.devices()}", flush=True)
    import warp as wp

    wp.init()
    print(f"warp {wp.__version__} device: {wp.get_device()}", flush=True)
    try:
        import mujoco_warp  # noqa: F401

        print("mujoco_warp: available (SolverMuJoCo enabled)", flush=True)
    except ImportError:
        print("mujoco_warp: unavailable (falling back to Featherstone)", flush=True)


def execute(experiment: str, preset: str) -> dict:
    """Run one experiment's example script and return a result record."""
    import os
    import subprocess
    import sys
    import time

    if preset not in PRESETS:
        raise ValueError(f"unknown preset {preset!r}; choose from {sorted(PRESETS)}")
    script = EXPERIMENTS[experiment]
    overrides = PRESETS[preset]

    report_device()
    print(f"\npreset {preset!r} -> {overrides or '(defaults)'}", flush=True)
    print(f"{'=' * 72}\n== {experiment} ({script})\n{'=' * 72}", flush=True)

    # PYTHONPATH, not cwd: Python puts the *script's* directory on sys.path, so
    # /root/examples is importable but /root (where xwm lives) is not.
    environment = {
        **os.environ,
        **{f"{ENV_PREFIX}{k}": v for k, v in overrides.items()},
        f"{ENV_PREFIX}OUTPUT_ROOT": OUTPUT_DIR,
        "PYTHONPATH": "/root",
    }
    start = time.time()
    # Streamed line by line rather than captured. A captured run is invisible
    # until it exits, which on a multi-hour training job means no way to tell
    # slow from hung -- and stderr merged into stdout so a traceback arrives in
    # place rather than after everything else.
    process = subprocess.Popen(  # noqa: S603
        [sys.executable, "-u", f"/root/examples/{script}.py"],
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        text=True,
        bufsize=1,
        cwd="/root",
        env=environment,
    )
    for line in process.stdout or ():
        sys.stdout.write(line)
        sys.stdout.flush()
    returncode = process.wait()
    return {
        "experiment": experiment,
        "script": script,
        "preset": preset,
        "returncode": returncode,
        "seconds": round(time.time() - start, 1),
    }


def collect_files() -> dict[str, bytes]:
    """Read every artifact out of the mounted volume."""
    root = pathlib.Path(OUTPUT_DIR)
    return {
        str(path.relative_to(root)): path.read_bytes()
        for path in sorted(root.rglob("*"))
        if path.is_file()
    }


def download(files: dict[str, bytes]) -> int:
    """Write collected artifacts into ``examples/outputs/``."""
    target = ROOT / "examples" / "outputs"
    for name, blob in files.items():
        path = target / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(blob)
    return len(files)
